-- P13: capturas de las estadísticas de cada uno (la página de su perfil en csstats.gg). Cada captura se guarda con la
-- fecha en que se cargó, y comparando dos se ve cómo ha ido entre medias.
CREATE TABLE capturas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugador_id  BIGINT        NOT NULL REFERENCES jugadores (id) ON DELETE CASCADE,
    juego       VARCHAR(20)   NOT NULL,
    -- De qué web es la captura (csstats).
    fuente      VARCHAR(30)   NOT NULL,
    cargada_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Los números de la captura, como JSON plano: los totales (partidas, kills, muertes...) y los valores del momento
    -- (K/D, rating, ADR...). Las claves son las de Capturas.CAMPOS.
    datos       VARCHAR(4000) NOT NULL DEFAULT '{}',
    -- Quién leyó los números: gemini (y el usuario los revisó) o a mano.
    leida_por   VARCHAR(10)   NOT NULL
);
CREATE INDEX capturas_jugador_idx ON capturas (jugador_id, juego, cargada_en);

-- Los mapas que salen en la captura (los más jugados y los de más éxito): partidas o winrate, el que se vea.
CREATE TABLE capturas_mapas (
    captura_id  BIGINT       NOT NULL REFERENCES capturas (id) ON DELETE CASCADE,
    mapa        VARCHAR(100) NOT NULL,
    partidas    INTEGER,
    winrate     DOUBLE PRECISION
);
CREATE INDEX capturas_mapas_captura_idx ON capturas_mapas (captura_id);

-- La imagen de cada captura, aparte para no cargarla al listar.
CREATE TABLE capturas_imagenes (
    captura_id  BIGINT       PRIMARY KEY REFERENCES capturas (id) ON DELETE CASCADE,
    tipo        VARCHAR(40)  NOT NULL,
    datos       BYTEA        NOT NULL
);
